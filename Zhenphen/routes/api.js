const express = require('express');
const { rateLimit } = require('express-rate-limit');
const { pool } = require('../db');
const { requireAuth, requireRole, asyncRoute } = require('../middleware/api');
const { createUserRepository } = require('../repositories/userRepository');
const { createEmailService } = require('../services/emailService');
const { createAuthController } = require('../controllers/authController');
const { createApiController } = require('../controllers/apiController');
const router = express.Router();
const users = createUserRepository(pool);
const auth = createAuthController({ users, emailService: createEmailService() });
const api = createApiController({ pool, users });
const loginLimiter = rateLimit({ windowMs: 15 * 60 * 1000, limit: 10, standardHeaders: true, legacyHeaders: false, message: { error: 'Too many requests. Please wait and try again later.' } });
const registerLimiter = rateLimit({ windowMs: 60 * 60 * 1000, limit: 5, standardHeaders: true, legacyHeaders: false, message: { error: 'Too many requests. Please wait and try again later.' } });
const applicationLimiter = rateLimit({ windowMs: 60 * 60 * 1000, limit: 10, standardHeaders: true, legacyHeaders: false, message: { error: 'Too many requests. Please wait and try again later.' } });
const passwordResetLimiter = rateLimit({ windowMs: 60 * 60 * 1000, limit: 5, standardHeaders: true, legacyHeaders: false, message: { error: 'Too many requests. Please wait and try again later.' } });
const verificationLimiter = rateLimit({ windowMs: 15 * 60 * 1000, limit: 30, standardHeaders: true, legacyHeaders: false, message: { error: 'Too many verification attempts. Please wait and try again later.' } });
const feedbackLimiter = rateLimit({ windowMs: 60 * 60 * 1000, limit: 5, standardHeaders: true, legacyHeaders: false, message: { error: 'Too many requests. Please wait and try again later.' } });

router.get('/auth/session', asyncRoute(auth.session));
router.post('/feedback', feedbackLimiter, asyncRoute(api.feedback));
router.post('/auth/register', registerLimiter, asyncRoute(auth.register));
router.post('/auth/verification/resend', passwordResetLimiter, asyncRoute(auth.resendVerification));
router.post('/auth/verification/confirm', verificationLimiter, asyncRoute(auth.verifyEmail));
router.post('/auth/login', loginLimiter, asyncRoute(auth.login));
router.post('/auth/password-reset/request', passwordResetLimiter, asyncRoute(auth.requestPasswordReset));
router.post('/auth/password-reset/confirm', passwordResetLimiter, asyncRoute(auth.confirmPasswordReset));
router.post('/auth/logout', requireAuth, asyncRoute(auth.logout));
router.post('/auth/heartbeat', requireAuth, asyncRoute(auth.heartbeat));
router.get('/profile', requireAuth, asyncRoute(api.profile));
router.put('/profile', requireAuth, asyncRoute(api.updateProfile));
router.post('/volunteer-applications', requireAuth, requireRole('student'), applicationLimiter, asyncRoute(api.applyVolunteer));
router.get('/site-content', asyncRoute(api.siteContent));
router.get('/member/activity', requireAuth, asyncRoute(api.memberActivity));
router.post('/donations/checkout', api.checkout);

module.exports = router;
